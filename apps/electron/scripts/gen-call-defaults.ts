/**
 * Writes src/main/team-calls/call-defaults.generated.ts (gitignored) with the
 * shared LiveKit defaults baked into the main-process bundle.
 * Source: ROX_CALLS_ENV_FILE (dotenv) or LIVEKIT_URL / LIVEKIT_API_KEY /
 * LIVEKIT_API_SECRET in the environment. Missing values → empty
 * (calls then need a Settings override). Never prints the values.
 */
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

const fromFile: Record<string, string> = {}
const file = process.env.ROX_CALLS_ENV_FILE
if (file && existsSync(file)) {
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const i = line.indexOf('=')
    if (i > 0 && !line.trimStart().startsWith('#')) fromFile[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '')
  }
}
const pick = (k: string) => process.env[k]?.trim() || fromFile[k] || ''
const values = {
  livekitUrl: pick('LIVEKIT_URL'),
  livekitApiKey: pick('LIVEKIT_API_KEY'),
  livekitApiSecret: pick('LIVEKIT_API_SECRET'),
}
const out = join(import.meta.dir, '../src/main/team-calls/call-defaults.generated.ts')
writeFileSync(out, `// GENERATED by scripts/gen-call-defaults.ts — gitignored, never commit.\nexport const CALL_DEFAULTS = ${JSON.stringify(values)} as const\n`, { mode: 0o600 })
console.log(`[gen-call-defaults] livekit=${values.livekitApiKey ? 'set' : 'empty'}`)
