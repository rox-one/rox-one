/**
 * Writes src/main/rox-defaults/rox-defaults.generated.ts (gitignored) with the
 * shared ROX gateway key baked into the main-process bundle, so every install
 * talks to api.rox.one (Rox R1 Max, gateway fallback to DeepSeek V4.1 Flash)
 * without a key prompt.
 * Source: ROX_API_KEY in the environment, else ROX_DEFAULTS_ENV_FILE (dotenv).
 * Missing value → empty string (the app then falls back to the key prompt).
 * Never prints the value.
 */
import { existsSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

export function parseDotenv(text: string): Record<string, string> {
  const out: Record<string, string> = {}
  for (const line of text.split('\n')) {
    const i = line.indexOf('=')
    if (i > 0 && !line.trimStart().startsWith('#')) {
      const key = line.slice(0, i).trim().replace(/^export\s+/, '')
      out[key] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '')
    }
  }
  return out
}

export function renderRoxDefaultsModule(apiKey: string): string {
  return `// GENERATED by scripts/gen-rox-defaults.ts — gitignored, never commit.\nexport const ROX_DEFAULTS = ${JSON.stringify({ roxApiKey: apiKey })} as const\n`
}

export const ROX_DEFAULTS_MODULE = join(import.meta.dir, '../src/main/rox-defaults/rox-defaults.generated.ts')

/**
 * Write the generated module. An empty key never clobbers an existing
 * generated file (a dev rebuild without the env keeps the last baked key);
 * a missing file is always created so the import resolves.
 */
export function writeRoxDefaultsModule(env: Record<string, string | undefined> = process.env, out = ROX_DEFAULTS_MODULE): 'set' | 'kept' | 'empty' {
  const file = env.ROX_DEFAULTS_ENV_FILE
  const fromFile = file && existsSync(file) ? parseDotenv(readFileSync(file, 'utf8')) : {}
  const roxApiKey = env.ROX_API_KEY?.trim() || fromFile.ROX_API_KEY?.trim() || ''
  if (!roxApiKey && existsSync(out)) return 'kept'
  writeFileSync(out, renderRoxDefaultsModule(roxApiKey), { mode: 0o600 })
  return roxApiKey ? 'set' : 'empty'
}

if (import.meta.main) {
  console.log(`[gen-rox-defaults] rox=${writeRoxDefaultsModule()}`)
}
