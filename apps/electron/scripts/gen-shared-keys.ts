/**
 * Writes src/main/home-fetch/shared-keys.local.ts (gitignored) from the build
 * machine's environment so shared keys are embedded into the main bundle.
 *
 *   EXA_API_KEY=...            direct value, or
 *   ROX_SHARED_KEYS_ENV=path   a KEY=VALUE env file containing EXA_API_KEY
 *
 * Never prints key values. With no key the file is removed so a stale key
 * cannot linger in a later build.
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const out = join(import.meta.dir, '../src/main/home-fetch/shared-keys.local.ts')

function fromEnvFile(path: string | undefined): Record<string, string> {
  if (!path || !existsSync(path)) return {}
  const vars: Record<string, string> = {}
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const m = /^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line)
    if (m) vars[m[1]!] = m[2]!.replace(/^['"]|['"]$/g, '')
  }
  return vars
}

const file = fromEnvFile(process.env.ROX_SHARED_KEYS_ENV)
const exa = (process.env.EXA_API_KEY ?? file.EXA_API_KEY ?? '').trim()

if (!exa) {
  if (existsSync(out)) rmSync(out)
  console.log('[gen-shared-keys] no shared keys configured; search widgets will report no-key')
} else {
  writeFileSync(out, `// Generated by scripts/gen-shared-keys.ts — gitignored, never commit.\nexport const SHARED_KEYS = ${JSON.stringify({ exa })}\n`, { mode: 0o600 })
  console.log('[gen-shared-keys] embedded: exa')
}
