test('a historical event requested before snapshot load resolves read-only in its original run', async ({ page, request }, info) => {
  const first = await (await request.post(`${server}/start`, { data: {} })).json()
  for (let step = 2; step < 16; step++) expect((await request.post(`${server}/step`, { data: {} })).ok()).toBe(true)
  const query = { workspaceId: 'fixture-workspace', sessionId: 'fixture-session', rootRunId: first.rootRunId }
  const old = await (await request.post(`${server}/snapshot`, { data: query })).json()
  const contextEvent = old.events.find((event: { kind: string }) => event.kind === 'context.captured')
  expect(contextEvent).toBeTruthy()
  const next = await (await request.post(`${server}/next-run`, { data: {} })).json()
  expect(next.rootRunId).not.toBe(first.rootRunId)
  const before = await (await request.get(`${server}/stats`)).json()
  await page.goto(`/?traceRoot=${encodeURIComponent(first.rootRunId)}&event=${encodeURIComponent(contextEvent.eventId)}`, { waitUntil: 'domcontentloaded' })
  await page.getByTestId('toggle-map').click()
  await expect(page.getByRole('combobox', { name: 'Выбрать запуск' })).toHaveValue(first.rootRunId)
  await expect(page.getByTestId('runtime-inspector')).toBeVisible()
  await expect(page.getByTestId('runtime-inspector')).toContainText('Сравни два источника')
  const after = await (await request.get(`${server}/stats`)).json()
  expect(after.runtimeStarts).toBe(before.runtimeStarts)
  expect(after.terminalExecutions).toBe(before.terminalExecutions)
  expect(after.providerRequests).toBe(0)
  await page.screenshot({ path: info.outputPath('historical-event-cold-snapshot.png'), fullPage: true })
})
